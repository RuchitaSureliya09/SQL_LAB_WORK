--11. Create trigger for storing updated employee details such as EID, old salary, new salary, old department,
--new department, and update date into EMPLOYEE_UPDATE_LOG table.

CREATE TABLE EMPLOYEE_UPDATE_LOG
(
    LOGID INT IDENTITY(1,1),
    EID INT,
    OLDSALARY DECIMAL(10,2),
    NEWSALARY DECIMAL(10,2),
    OLDDEPARTMENT VARCHAR(100),
    NEWDEPARTMENT VARCHAR(100),
    UPDATEDATE DATETIME
)

--FOR MULTIPLE ROWS

CREATE OR ALTER TRIGGER TR_EMPLOYEE_UPDATE_LOG
ON EMPLOYEE
FOR UPDATE
AS
BEGIN
    INSERT INTO EMPLOYEE_UPDATE_LOG
    (
        EID, OLDSALARY, NEWSALARY,
        OLDDEPARTMENT, NEWDEPARTMENT, UPDATEDATE
    )
    SELECT
        D.EID, D.SALARY, I.SALARY,
        D.DEPARTMENT, I.DEPARTMENT, GETDATE()
    FROM DELETED D
    INNER JOIN INSERTED I
    ON D.EID = I.EID
END

DROP TRIGGER TR_EMPLOYEE_UPDATE_LOG



