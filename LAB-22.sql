--14. Display customers whose amount is greater than previous customer's amount.
WITH CTE_PREVIOUS AS
(
  SELECT *,
  LAG(AMOUNT)
  OVER(ORDER BY AMOUNT) AS PREVIOUS_AMOUNT
  FROM CUSTOMER_ALL
)
SELECT * 
FROM CTE_PREVIOUS
WHERE AMOUNT > PREVIOUS_AMOUNT


--15. Display customers whose rank and dense rank are different.
WITH CTE_DIFF AS
(
  SELECT * ,
  DENSE_RANK()
  OVER(ORDER BY AMOUNT) AS D_RANK,
  RANK()
  OVER(ORDER BY AMOUNT) AS N_RANK
  FROM CUSTOMER_ALL
)
SELECT *
FROM CTE_DIFF
WHERE D_RANK <> N_RANK


--16. Display orders whose amount is neither highest nor lowest in their category.
WITH CTE_AMOUNT AS
(
  SELECT *, 
  MAX(AMOUNT) 
  OVER(PARTITION BY CATEGORY) AS FIRST_AMOUNT,
  MIN(AMOUNT) 
  OVER(PARTITION BY CATEGORY) AS LAST_AMOUNT
  FROM CUSTOMER_ALL
)
SELECT * 
FROM CTE_AMOUNT
WHERE AMOUNT <> FIRST_AMOUNT AND AMOUNT <> LAST_AMOUNT


--17. Display category-wise difference between highest and lowest amount.
WITH CTE_DIFF AS
(
  SELECT CATEGORY, 
  (MAX(AMOUNT) - MIN(AMOUNT)) AS DIFF
  FROM CUSTOMER_ALL
  GROUP BY CATEGORY
)
SELECT * 
FROM CTE_DIFF


--18. Display customers whose amount is greater than all FURNITURE category orders.
WITH CTE_FURNITURE AS
(
  SELECT MAX(AMOUNT) AS MAX_AMOUNT
  FROM CUSTOMER_ALL
  WHERE CATEGORY = 'FURNITURE'
)
SELECT *
FROM CUSTOMER_ALL CA
CROSS JOIN CTE_FURNITURE C
WHERE CA.AMOUNT > C.MAX_AMOUNT


--19. Display categories where all orders are above 10000.
WITH CTE_CATEGORY AS
(
  SELECT CATEGORY , MIN(AMOUNT) AS MIN_AMOUNT
  FROM CUSTOMER_ALL
  GROUP BY CATEGORY
)
SELECT CATEGORY 
FROM CTE_CATEGORY
WHERE MIN_AMOUNT > 10000


--20. Display customers whose amount difference from category topper is minimum.
WITH CTE_TOPPER AS (
    SELECT * , MAX(AMOUNT) 
	OVER(PARTITION BY CATEGORY) AS MAX_AMOUNT
    FROM CUSTOMER_ALL
),
CTE_DIFF AS (
    SELECT * ,
    (MAX_AMOUNT - AMOUNT) AS AMOUNT_DIFF
    FROM CTE_TOPPER
)
SELECT *
FROM CTE_DIFF
WHERE AMOUNT_DIFF = 0
