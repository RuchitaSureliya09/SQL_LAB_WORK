--15. Implement INSTEAD OF INSERT trigger on EMPLOYEE table to automatically remove extra spaces from FIRSTNAME and LASTNAME before insertion.

--FOR MULTIPLE ROWS

CREATE OR ALTER TRIGGER TR_REMOVE_SPACES
ON EMPLOYEE
INSTEAD OF INSERT
AS
BEGIN
    INSERT INTO EMPLOYEE
    (
        EID, FIRSTNAME, LASTNAME,
        DEPARTMENT, SALARY, CITY,
        GENDER, JOININGYEAR
    )
    SELECT
        EID,
        LTRIM(RTRIM(FIRSTNAME)),
        LTRIM(RTRIM(LASTNAME)),
        DEPARTMENT, SALARY, CITY,
        GENDER, JOININGYEAR
    FROM INSERTED
END

DROP TRIGGER TR_REMOVE_SPACES
