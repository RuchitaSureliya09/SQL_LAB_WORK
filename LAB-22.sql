SELECT * FROM CUSTOMER_ALL


--1. Display top 3 highest amount orders.
WITH CTE_TOP3 AS
(
  SELECT *,
  DENSE_RANK()
  OVER (ORDER BY AMOUNT DESC) AS AMOUNT_RANK
  FROM CUSTOMER_ALL
)
SELECT *
FROM CTE_TOP3
WHERE AMOUNT_RANK <= 3


--2. Display second highest order amount.
WITH CTE_2_HIGHEST AS
(
  SELECT *,
  DENSE_RANK()
  OVER (ORDER BY AMOUNT DESC) AS AMOUNT_RANK
  FROM CUSTOMER_ALL
)
SELECT *
FROM CTE_2_HIGHEST
WHERE AMOUNT_RANK = 2


--3. Display customers whose order amount is greater than category average amount.
WITH CTE_AMOUNT AS
(
  SELECT CATEGORY ,
		 AVG(AMOUNT) AS AVG_AMOUNT
  FROM CUSTOMER_ALL
  GROUP BY CATEGORY
)
SELECT CA.*
FROM CUSTOMER_ALL CA
INNER JOIN CTE_AMOUNT C
ON CA.CATEGORY = C.CATEGORY
WHERE AMOUNT > AVG_AMOUNT


--4. Display categories having average amount greater than 30000.
WITH CTE_CATEGORY_AMOUNT AS
(
  SELECT CATEGORY ,
		 AVG(AMOUNT) AS AVG_AMOUNT
  FROM CUSTOMER_ALL
  GROUP BY CATEGORY
)
SELECT CATEGORY , AVG_AMOUNT
FROM CTE_CATEGORY_AMOUNT
WHERE AVG_AMOUNT > 30000


--5. Display highest amount order from each category.
WITH CTE_HIGH_AMOUNT AS
(
  SELECT *,
  DENSE_RANK()
  OVER(PARTITION BY CATEGORY ORDER BY AMOUNT DESC) AS HA_RANK
  FROM CUSTOMER_ALL
)
SELECT *
FROM CTE_HIGH_AMOUNT
WHERE HA_RANK = 1


--6. Display lowest amount order from each category.
WITH CTE_LOW_AMOUNT AS
(
  SELECT *,
  DENSE_RANK()
  OVER(PARTITION BY CATEGORY ORDER BY AMOUNT ASC) AS LA_RANK
  FROM CUSTOMER_ALL
)
SELECT *
FROM CTE_LOW_AMOUNT
WHERE LA_RANK = 1


--7. Display categories having more than 3 orders.
WITH CTE_COUNT_ORDER AS
(
  SELECT CATEGORY ,
		 COUNT(*) AS TOTAL_ORDER
  FROM CUSTOMER_ALL
  GROUP BY CATEGORY
)
SELECT CATEGORY ,TOTAL_ORDER
FROM CTE_COUNT_ORDER
WHERE TOTAL_ORDER > 3


--8. Display city-wise total order amount.
WITH CTE_CITY_AMOUNT AS
(
  SELECT CITY ,
		 SUM(AMOUNT) AS TOTAL_AMOUNT
  FROM CUSTOMER_ALL
  GROUP BY CITY
)
SELECT CITY , TOTAL_AMOUNT
FROM CTE_CITY_AMOUNT


--9. Display category having highest average order amount.
WITH CTE_HIGH_AVG_AMOUNT AS
(
  SELECT CATEGORY ,
		 AVG(AMOUNT) AS AVG_ORDER
  FROM CUSTOMER_ALL
  GROUP BY CATEGORY
)
SELECT TOP 1 CATEGORY , AVG_ORDER
FROM CTE_HIGH_AVG_AMOUNT
ORDER BY AVG_ORDER DESC


--10. Display cumulative order amount in ascending order of amount.
WITH CTE_CUMULATIVE AS
(
  SELECT *, SUM(AMOUNT) 
  OVER(ORDER BY AMOUNT) AS TOTAL
  FROM CUSTOMER_ALL
)
SELECT * 
FROM CTE_CUMULATIVE


--11. Display category-wise top 2 highest amount orders.
WITH CTE_CATEGORY_AMOUNT AS
(
  SELECT *,
  DENSE_RANK()
  OVER(PARTITION BY CATEGORY ORDER BY AMOUNT DESC) AS A_RANK
  FROM CUSTOMER_ALL
)
SELECT *
FROM CTE_CATEGORY_AMOUNT
WHERE A_RANK <= 2


--12. Display customers whose amount is closest to category average amount.
WITH CTE_CLOSET AS
(
  SELECT AVG(AMOUNT) AS AVG_AMOUNT
  FROM CUSTOMER_ALL
  GROUP BY CATEGORY
),
CTE_DIFFERENCE AS
(
  SELECT * , ABS(AMOUNT - AVG_AMOUNT) AS DIFF_AMOUNT
  FROM CUSTOMER_ALL
  CROSS JOIN CTE_CLOSET
)
SELECT TOP 1 * 
FROM CTE_DIFFERENCE
ORDER BY DIFF_AMOUNT

