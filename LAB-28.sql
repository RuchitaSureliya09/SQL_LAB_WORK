--5. Create trigger for automatically converting CITY names into uppercase during insertion.

--FOR A SINGLE ROW

CREATE OR ALTER TRIGGER TR_CITY_CONVERT
ON EMPLOYEE
FOR INSERT
AS
BEGIN
	DECLARE @CITY VARCHAR(30)
	DECLARE @EID INT

	SELECT @CITY = CITY FROM INSERTED
	SELECT @EID = EID FROM INSERTED

	UPDATE EMPLOYEE
	SET CITY = UPPER(@CITY)
	WHERE EID = @EID
END

DROP TRIGGER TR_CITY_CONVERT

--------------------- OR ----------------------

--FOR MULTIPLE ROWS

CREATE OR ALTER TRIGGER TR_CITY_CONVERT
ON EMPLOYEE
AFTER INSERT
AS
BEGIN
    UPDATE E
    SET E.CITY = UPPER(E.CITY)
    FROM EMPLOYEE E
    INNER JOIN INSERTED I
    ON E.EID = I.EID
END

DROP TRIGGER TR_CITY_CONVERT



--6. Create trigger for updating employee city and printing old city and new city name.

--FOR A SINGLE ROW

CREATE OR ALTER TRIGGER TR_PRINT_CITY
ON EMPLOYEE
FOR UPDATE
AS
BEGIN
	DECLARE @CITY1 VARCHAR(20)
	DECLARE @CITY2 VARCHAR(20)
	DECLARE @EID INT

	SELECT @CITY1 = CITY FROM INSERTED
	SELECT @CITY2 = CITY FROM DELETED
	SELECT @EID = EID FROM INSERTED

	PRINT 'EID : ' + CAST(@EID AS VARCHAR(10))
	PRINT 'OLD CITY' + @CITY2
	PRINT 'NEW CITY' + @CITY1
END

DROP TRIGGER TR_PRINT_CITY

-------------------------- OR ------------------------------

--FOR MULTIPLE ROWS

CREATE OR ALTER TRIGGER TR_PRINT_CITY
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
    IF UPDATE(CITY)
    BEGIN
        SELECT
            I.EID,
            'OLD CITY : ' + ISNULL(D.CITY, 'NULL') AS OLD_CITY,
            'NEW CITY : ' + ISNULL(I.CITY, 'NULL') AS NEW_CITY
        FROM INSERTED I
        INNER JOIN DELETED D
        ON I.EID = D.EID
    END
END

DROP TRIGGER TR_PRINT_CITY



